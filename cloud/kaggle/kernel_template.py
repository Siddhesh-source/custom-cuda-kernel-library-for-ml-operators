"""ccml build and correctness run, executed on a Kaggle kernel.

Generated by cloud/kaggle/kaggle_run.py -- do not edit the copy under _build/,
edit this template. The repository is embedded below as a base64 tar.gz, so this
script is self-contained and needs no internet access.
"""

import base64
import io
import os
import re
import shutil
import subprocess
import sys
import tarfile

PAYLOAD = "__CCML_PAYLOAD__"

WORK = "/kaggle/working"

# Source and build live OUTSIDE /kaggle/working on purpose. Everything under
# /kaggle/working becomes kernel output, and a CMake build tree is thousands of
# files -- large enough that fetching the output times out before reaching the
# log. Only the log is written to /kaggle/working, so the download is one file.
SCRATCH = "/tmp/ccml-work"
SOURCE = os.path.join(SCRATCH, "src")
BUILD = os.path.join(SCRATCH, "build")
LOG_PATH = os.path.join(WORK, "ccml_build_log.txt")

# Fallback when no GPU is attached. Matches the Kaggle T4 benchmark target, so the
# compile-only path still exercises the real target architecture.
FALLBACK_ARCHITECTURE = "75"

class _StepFailed(Exception):
    """Raised when a build or test step fails, to unwind without exiting non-zero."""


log_file = open(LOG_PATH, "w", encoding="utf-8")


def emit(text=""):
    print(text)
    log_file.write(text + "\n")
    log_file.flush()


def run(label, command, cwd=None, check=True, env=None):
    emit()
    emit("=" * 72)
    emit(label)
    emit("$ " + " ".join(command))
    emit("=" * 72)

    merged_env = None
    if env:
        merged_env = dict(os.environ)
        merged_env.update(env)

    completed = subprocess.run(
        command, cwd=cwd, env=merged_env,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    emit(completed.stdout.rstrip())

    if check and completed.returncode != 0:
        emit("")
        emit("!! STEP FAILED: " + label + " (exit code "
             + str(completed.returncode) + ")")
        emit("!! CCML_RUN_FAILED")
        emit("")
        emit("Stopping here. The log is still written to " + LOG_PATH + " so the")
        emit("failure can be read; exiting non-zero would make Kaggle discard it.")
        log_file.close()
        raise _StepFailed(label)
    return completed.returncode, completed.stdout


def unpack():
    shutil.rmtree(SCRATCH, ignore_errors=True)
    os.makedirs(SOURCE, exist_ok=True)
    archive = io.BytesIO(base64.b64decode(PAYLOAD))
    with tarfile.open(fileobj=archive, mode="r:gz") as tar:
        members = tar.getmembers()
        tar.extractall(SOURCE)
    emit("unpacked " + str(len(members)) + " files into " + SOURCE)


def detect_gpu():
    """Return (name, architecture) or (None, None) when no GPU is attached."""
    try:
        completed = subprocess.run(
            ["nvidia-smi", "--query-gpu=name,compute_cap", "--format=csv,noheader"],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    except FileNotFoundError:
        return None, None

    if completed.returncode != 0 or not completed.stdout.strip():
        return None, None

    first = completed.stdout.strip().splitlines()[0]
    name, compute_cap = (part.strip() for part in first.split(","))
    return name, compute_cap.replace(".", "")


def cmake_version():
    try:
        completed = subprocess.run(
            ["cmake", "--version"],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    except FileNotFoundError:
        return (0, 0, 0), "not installed"

    match = re.search(r"(\d+)\.(\d+)\.(\d+)", completed.stdout)
    if not match:
        return (0, 0, 0), completed.stdout.strip()
    return tuple(int(part) for part in match.groups()), completed.stdout.strip()


def ensure_toolchain():
    """Make sure cmake is new enough and pick a generator that exists."""
    version, text = cmake_version()
    emit("cmake: " + text.splitlines()[0] if text else "cmake: missing")

    if version < (3, 25):
        emit("cmake is older than the 3.25 this project requires; "
             "trying to install a newer one from pip")
        run("Install cmake", [sys.executable, "-m", "pip", "install", "-q",
                              "cmake"], check=False)
        version, text = cmake_version()
        emit("cmake now: " + (text.splitlines()[0] if text else "still missing"))

    if version < (3, 25):
        emit("")
        emit("!! cmake is still too old and there is no internet access to "
             "upgrade it.")
        emit("   Re-push with enable_internet set to true, or lower "
             "cmake_minimum_required.")
        log_file.close()
        sys.exit(1)

    generator = "Ninja"
    if shutil.which("ninja") is None:
        run("Install ninja", [sys.executable, "-m", "pip", "install", "-q",
                              "ninja"], check=False)
        if shutil.which("ninja") is None:
            generator = "Unix Makefiles"
            emit("ninja unavailable; falling back to " + generator)
    emit("generator: " + generator)
    return generator


def main():
    emit("ccml remote build on Kaggle")
    emit("python: " + sys.version.split()[0])

    unpack()

    run("CUDA toolkit", ["nvcc", "--version"])

    gpu_name, architecture = detect_gpu()
    if gpu_name is None:
        architecture = FALLBACK_ARCHITECTURE
        emit("")
        emit("No GPU attached. Compiling for sm_" + architecture
             + "; kernels will not be run.")
        emit("Enable the GPU accelerator on the kernel to run them.")
    else:
        run("GPU and driver", ["nvidia-smi"], check=False)
        emit("")
        emit("Detected " + gpu_name + ", building for sm_" + architecture)

    generator = ensure_toolchain()

    # cuDNN ships inside the PyTorch wheel; point the bench's optional cuDNN
    # baseline at it.
    cudnn_root = ""
    try:
        import nvidia.cudnn  # noqa: F401
        cudnn_root = list(nvidia.cudnn.__path__)[0]
        emit("cuDNN from the PyTorch wheel: " + cudnn_root)
    except Exception as error:  # noqa: BLE001
        emit("cuDNN not importable (" + str(error) + "); cuDNN baseline disabled")

    run("Configure", [
        "cmake", "-S", SOURCE, "-B", BUILD,
        "-G", generator,
        "-DCMAKE_BUILD_TYPE=Release",
        "-DCCML_CUDA_ARCHITECTURES=" + architecture,
        # On deliberately: any warning in code this new is a finding.
        "-DCCML_WARNINGS_AS_ERRORS=ON",
        "-DCUDNN_ROOT=" + cudnn_root,
    ])
    run("Build", ["cmake", "--build", BUILD, "--parallel"])
    run("Install rules", ["cmake", "--install", BUILD,
                          "--prefix", os.path.join(SCRATCH, "install")])

    # On a CPU kernel this reports no device; that it runs proves linking works.
    run("Device properties", [os.path.join(BUILD, "bin", "ccml_device_query")],
        check=False)
    run("Usage example", [os.path.join(BUILD, "bin", "ccml_usage")], check=False)

    if gpu_name is None:
        emit()
        emit("Skipping the GPU job: no GPU attached.")
        log_file.close()
        return

    # Everything else is defined in the repository, so a task branch changes
    # what a session does without touching this template.
    commit = ""
    commit_file = os.path.join(SOURCE, ".ccml_commit")
    if os.path.exists(commit_file):
        commit = open(commit_file, encoding="utf-8").read().strip()
    run("GPU job (scripts/kaggle_job.sh)",
        ["bash", os.path.join(SOURCE, "scripts", "kaggle_job.sh"), SOURCE, BUILD,
         os.path.join(WORK, "out")],
        check=False, env={"CCML_COMMIT": commit})

    emit()
    emit("done. Full log written to " + LOG_PATH)
    log_file.close()


try:
    main()
except _StepFailed as failure:
    # Deliberately not re-raised: the kernel must finish successfully for Kaggle
    # to preserve /kaggle/working, and the log already records what went wrong.
    print("step failed: " + str(failure))
